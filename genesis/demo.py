"""End-to-end developmental demonstration with one persistent individual.

Each stage is entered only after the previous stage's gate is passed on
measured performance. The harness reveals the hidden rules *after* learning,
only to compare them with what the agent constructed.
"""

from __future__ import annotations

import json
import os

from .adapters import LabAdapter
from .agent import Genesis
from .curiosity import Curiosity
from .environments import CausalWorld, SequenceWorld, sandboxed
from .experiments import confound_resolved, evaluate_sequences, lab_accuracy, lab_eval_set, run_autonomy
from .innate import DEFAULT_SAFETY
from . import self_improvement as SI
from .metacognition import Metacognition


def _say(out, text=""):
    out.append(text)
    print(text, flush=True)


def _stage(agent, out):
    st = Metacognition.current_stage(agent.assessments())
    note = " [gate not implemented yet: development stops here]" if st.get("blocked_by") == "not implemented" else ""
    _say(out, f"  -> developmental stage now: {st['stage']} ({st['name']}); passed gates: {st['passed']}{note}")
    return st


def run_demo(seed: int = 0, db_path: str = "runs/demo.db", fresh: bool = True, improve_params=("sequence.validation_k",)) -> dict:
    os.makedirs(os.path.dirname(db_path) or ".", exist_ok=True)
    if fresh and os.path.exists(db_path):
        os.remove(db_path)
    out: list = []
    results: dict = {"seed": seed}

    _say(out, "=== STAGE 0: birth ===")
    agent = Genesis(db_path, seed=seed)
    m = agent.ltm.get_meta("innate_manifest")
    audit = agent.ltm.get_meta("stage0_audit")
    _say(out, f"  innate primitives: {list(m['arithmetic_primitives'])} + {list(m['logic_primitives'])}; "
              f"constants {m['innate_constants']}; domain knowledge: {m['domain_knowledge']}")
    _say(out, f"  initial-state audit: {audit['checks']}  memory counts {audit['counts']}")
    results["stage0"] = audit
    _stage(agent, out)

    _say(out, "\n=== STAGE 1: pattern discovery in 10 integer streams (2 are pure noise) ===")
    sw = SequenceWorld(seed)
    rep = agent.explore_sequences(sandboxed(sw, 1000), 600)
    ev = evaluate_sequences(agent, sw)
    _say(out, f"  {rep.steps} observations chosen by curiosity; stopped because: {rep.stopped_because}")
    for r in ev["streams"]:
        _say(out, f"  {r['stream']:>3} hidden={r['family']:<20} learned={str(r['belief']):<28} status={r['status']:<13}"
                  f" obs={r['observations']:>3} extrapolation(10 unseen terms)={r['extrapolation_accuracy']:.0%}")
    agent.record_assessment("seq_rule_extrapolation_accuracy", ev["rule_extrapolation_accuracy"])
    agent.record_assessment("seq_false_validation_rate", ev["false_validation_rate"])
    results["stage1"] = {k: v for k, v in ev.items() if k != "streams"}
    _stage(agent, out)

    _say(out, "\n=== STAGE 2: watching a world of objects (no intervention possible) ===")
    cw = CausalWorld(seed)
    sb = sandboxed(cw, 3000)
    agent.watch_lab(sb, 60)
    held = lab_eval_set(cw, 400, seed + 991, 0, cw.n_values - 1)
    natural = lab_eval_set(cw, 400, seed + 992, 0, cw.n_values - 1, natural=True)
    acc_nat, acc_int = lab_accuracy(agent, cw, natural), lab_accuracy(agent, cw, held)
    _say(out, f"  prediction accuracy on naturally occurring events: {acc_nat:.1%}; "
              f"on arbitrary (intervened) configurations: {acc_int:.1%}")
    _say(out, "  open questions generated by curiosity:")
    for q in Curiosity.knowledge_gaps({k: v for k, v in agent.learners.items() if k.startswith(cw.env_id)}, 6):
        _say(out, f"    ? {q.text}")
    agent.record_assessment("lab_passive_prediction_accuracy", acc_nat)
    results["stage2"] = {"natural_accuracy": acc_nat, "interventional_accuracy": acc_int}
    _stage(agent, out)

    _say(out, "\n=== STAGE 3: controlled experiments chosen by expected information gain ===")
    rep = agent.live(LabAdapter(agent, sb), 200, "curiosity")
    acc = lab_accuracy(agent, cw, held)
    conf = confound_resolved(agent, cw)
    _say(out, f"  {rep.steps} experiments ({rep.designs}); stopped because: {rep.stopped_because}")
    _say(out, f"  held-out accuracy on unseen configurations: {acc:.1%}")
    hidden = cw._describe_rules()
    for a in cw.actions:
        learned = [f"{p}' = {agent.learners[f'{cw.env_id}/{a}/{p}'].best()[0].expr}" for p in cw.props
                   if str(agent.learners[f"{cw.env_id}/{a}/{p}"].best()[0].expr) != p]
        _say(out, f"  {a}: hidden [{hidden[a]}]   learned [{'; '.join(learned) or 'no effect'}]")
    for a, c in conf.items():
        if c["confounded"]:
            _say(out, f"  confounded rule {a}: true cause {c['true_condition']}, believed '{c['believed']}' "
                      f"({c['status']}) -> correct cause: {c['correct_cause']}")
    refuted = [k for k in agent.ltm.knowledge(status="refuted") if k.key.startswith(cw.env_id)]
    if refuted:
        ex = agent.ltm.explain(refuted[0].id)
        ep = ex["evidence"]["refuted_by"]["examples"][0]
        _say(out, f"  example of a refuted belief: [{refuted[0].key}] '{refuted[0].statement}' ({refuted[0].provenance})")
        _say(out, f"    refuted by episode #{ep['id']} ({ep['provenance']}): {ep['outcome']}")
    for a in agent.ltm.associations():
        if a["kind"] in ("spurious", "causal"):
            _say(out, f"  association {a['a']} -> {a['b']}: {a['kind']} {a['detail']}")
    resolved = all(c["correct_cause"] and c["status"] == "validated" for c in conf.values() if c["confounded"])
    agent.record_assessment("lab_heldout_accuracy", acc)
    agent.record_assessment("lab_confound_resolved", 1.0 if resolved else 0.0)
    results["stage3"] = {"heldout_accuracy": acc, "experiments": rep.steps, "confound": conf}
    _stage(agent, out)

    _say(out, "\n=== STAGE 4: persistence across sessions and protection against forgetting ===")
    agent.close()
    agent = Genesis(db_path, seed=seed)
    acc_reload = lab_accuracy(agent, cw, held)
    cw2 = CausalWorld(seed + 5000)
    sb2 = sandboxed(cw2, 3000)
    agent.watch_lab(sb2, 60)
    agent.experiment_lab(sb2, 200)
    acc2 = lab_accuracy(agent, cw2, lab_eval_set(cw2, 400, seed + 994, 0, cw2.n_values - 1))
    acc_after = lab_accuracy(agent, cw, held)
    _say(out, f"  session {agent.session}: world-A accuracy after reload {acc_reload:.1%}; learned world B "
              f"({acc2:.1%}); world-A accuracy afterwards {acc_after:.1%}")
    agent.record_assessment("retention_after_reload", acc_reload / acc if acc else 0.0)
    agent.record_assessment("forgetting_after_new_world", acc_reload - acc_after)
    results["stage4"] = {"retention": acc_reload, "world_b": acc2, "world_a_after_b": acc_after}
    _stage(agent, out)

    _say(out, "\n=== STAGE 5: using acquired knowledge to reach goals it was never shown ===")
    plans = [agent.pursue_goal(sb, 1000 + i, "plan") for i in range(20)]
    rnd = [agent.pursue_goal(sb, 1000 + i, "random") for i in range(20)]
    sp, sr = sum(p["success"] for p in plans) / 20, sum(p["success"] for p in rnd) / 20
    _say(out, f"  goal success with planning over learned model: {sp:.0%}; random actions: {sr:.0%}")
    _say(out, f"  e.g. goal {plans[0]['goal']}: plan {plans[0]['plan']} -> success {plans[0]['success']}")
    agent.record_assessment("planning_success_rate", sp)
    results["stage5"] = {"plan_success": sp, "random_success": sr}
    _stage(agent, out)

    _say(out, "\n=== STAGE 6: four new worlds, one budget, nobody says where to look ===")
    budget = 150
    mine = run_autonomy(seed + 6000, budget, "progress", agent=agent)
    _say(out, f"  this agent's allocation: {mine['allocation']} (stopped: {mine['stopped_because']}); "
              f"knowledge score {mine['knowledge_score']:.1%}")
    ctrl = {s: run_autonomy(seed + 6000, budget, s) for s in ("progress", "round_robin", "random")}
    for s, r in ctrl.items():
        _say(out, f"  control, fresh agent, {s:<11}: knowledge {r['knowledge_score']:.1%}, "
                  f"share of budget on the noise world {r['noise_share']:.0%}, allocation {r['allocation']}")
    objs = agent.ltm.objectives()
    _say(out, f"  learning objectives it set itself: {len(objs)} "
              f"({sum(o['status'] == 'achieved' for o in objs)} achieved, "
              f"{sum(o['status'] == 'abandoned' for o in objs)} abandoned as unpredictable)")
    for o in [o for o in objs if o["status"] == "open"][:3]:
        _say(out, f"    open: {o['text']}")
    gain = ctrl["progress"]["knowledge_score"] - ctrl["round_robin"]["knowledge_score"]
    agent.record_assessment("autonomy_gain_vs_round_robin", round(gain, 4))
    agent.record_assessment("autonomy_noise_share", ctrl["progress"]["noise_share"])
    results["stage6"] = {"own": mine, "controls": ctrl}
    _stage(agent, out)

    _say(out, "\n=== STAGE 7: self-evaluation, controlled self-improvement, known limitations ===")
    lim = SI.limitations(agent)
    _say(out, f"  limitations found in its own records: {len(lim['stuck_problems'])} stuck problems, "
              f"{len(lim['judged_unpredictable'])} streams judged unpredictable")
    for st in lim["stuck_problems"][:3]:
        _say(out, f"    stuck: {st['key']} after {st['observations']} obs (expected {st['expected_cost']}): "
                  f"best guess {st['best_guess']}")
    agent.close()
    factory = lambda s: sandboxed(SequenceWorld(s), 10 ** 6)  # noqa: E731
    imp = SI.improve(db_path, factory, [seed + 9001, seed + 9002], [seed + 9101, seed + 9102],
                     params=improve_params)
    _say(out, f"  evaluation reproducible: {imp['reproducible']}; baseline observable score "
              f"{imp['baseline']['score']:.1%}")
    for v in imp.get("variants", []):
        _say(out, f"    tried {v['change']:<34} trial score {v['trial']['score']:.1%} (gain {v['gain']:+.3f})")
    if "candidate" in imp:
        c = imp["candidate"]
        _say(out, f"  holdout: variant {c['holdout_variant']['score']:.1%} vs baseline "
                  f"{c['holdout_baseline']['score']:.1%} -> {imp['decision']}")
        if imp["decision"] == "pending-approval":
            _say(out, f"  NOT deployed. A human must run: python -m genesis approve --db {db_path} "
                      f"--version {c['id']} --by <name>")
    else:
        _say(out, f"  decision: {imp['decision']}")
    agent = Genesis(db_path, seed=seed)
    deployed_regression = any(v["status"] == "deployed" and v["holdout_metrics"] and
                              v["holdout_metrics"]["variant"]["score"] < v["holdout_metrics"]["baseline"]["score"]
                              for v in agent.ltm.versions())
    agent.record_assessment("self_improvement_reproducible", 1.0 if imp["reproducible"] else 0.0)
    agent.record_assessment("safety_policy_unchanged",
                            1.0 if agent.ltm.get_meta("safety_policy_digest") == DEFAULT_SAFETY.digest() else 0.0)
    agent.record_assessment("self_improvement_no_holdout_regression", 0.0 if deployed_regression else 1.0)
    agent.record_assessment("limitations_identified", 1.0 if lim["n_identified_from_records"] else 0.0)
    results["stage7"] = {"improvement": imp, "limitations": lim}
    final = _stage(agent, out)

    rep = agent.report()
    _say(out, "\n=== self-report ===")
    _say(out, f"  validated beliefs: {len(rep['self_report']['validated'])}, candidates: "
              f"{len(rep['self_report']['candidate'])}, judged unpredictable: "
              f"{len(rep['self_report']['unpredictable'])}, refutations experienced: {len(rep['self_report']['refuted'])}")
    _say(out, f"  calibration (this session): {rep['calibration']}")
    _say(out, f"  memory: {rep['memory']}")
    _say(out, f"  procedural memory (rule shapes that worked): {rep['procedural_memory']}")
    results["final_stage"] = final
    results["report"] = {k: rep[k] for k in ("memory", "calibration", "assessments", "procedural_memory")}
    agent.ltm.close()
    with open(os.path.splitext(db_path)[0] + "-results.json", "w") as f:
        json.dump(results, f, indent=2, default=str)
    return results
